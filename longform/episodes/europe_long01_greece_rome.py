# ---------------------------------------------------------------- サムネイル（1280x720）
def thumbnail(path):
    import math
    from PIL import Image, ImageDraw
    from engine.core import STAGE_H, STAGE_Y, W as VW, WorldMap, font, merc, text_w
    z = 30
    # アテネが右寄り、ローマが中央付近に来るカメラ
    clon = ATHENS[0] - (1060 * STAGE_H / 720 + (VW - STAGE_H * 1280 / 720) - VW / 2) / z
    my = merc(ATHENS[1]) + (430 * STAGE_H / 720 - STAGE_H / 2) / z
    clat = math.degrees(2 * math.atan(math.exp(math.radians(my))) - math.pi / 2)
    cam = (clon, clat, z)
    m = WorldMap()
    x0 = VW - STAGE_H * 1280 / 720
    k = 720 / STAGE_H
    im = m.view(cam).crop((int(x0), 0, VW, STAGE_H)).resize((1280, 720)).convert("RGBA")

    def to(lon, lat):
        x, y = m.to_screen(cam, lon, lat)
        return (x - x0) * k, (y - STAGE_Y) * k

    L = Image.new("RGBA", (1280, 720), (0, 0, 0, 0))
    d = ImageDraw.Draw(L)
    for x in range(0, 820):
        a = 238 if x < 600 else int(238 * (820 - x) / 220)
        d.line([(x, 0), (x, 720)], fill=(*PAL["bg"], a))
    pts = [to(*ATHENS), to(19.0, 39.6), to(15.2, 41.8), to(*ROME)]
    d.line(pts, fill=PAL["white"], width=22, joint="curve")
    d.line(pts, fill=PAL["gold"], width=12, joint="curve")
    (xa, ya), (xb, yb) = pts[-2], pts[-1]
    ang = math.atan2(yb - ya, xb - xa)
    tip = (xb + math.cos(ang) * 10, yb + math.sin(ang) * 10)
    d.polygon([tip, (xb - math.cos(ang - 0.6) * 38, yb - math.sin(ang - 0.6) * 38),
               (xb - math.cos(ang + 0.6) * 38, yb - math.sin(ang + 0.6) * 38)], fill=PAL["gold"])
    for (lo, la), name, side in ((ATHENS, "アテネ", 1), (ROME, "ローマ", 1), (KNOSSOS, "クレタ", 1)):
        x, y = to(lo, la)
        d.ellipse([x - 15, y - 15, x + 15, y + 15], fill=PAL["red"], outline=PAL["white"], width=5)
        d.text((x + 24 * side, y), name, font=font("black", 44), fill=PAL["red"], anchor="lm" if side > 0 else "rm",
               stroke_width=7, stroke_fill=PAL["white"])
    d.rectangle([0, 0, 1280, 64], fill=PAL["ink"])
    d.rounded_rectangle([20, 12, 250, 52], radius=20, fill=PAL["gold"])
    d.text((135, 32), "世界史ずかん", font=font("black", 28), fill=PAL["ink"], anchor="mm")
    d.text((270, 32), "ヨーロッパ編 長編", font=font("black", 28), fill=PAL["white"], anchor="lm")
    d.text((48, 96), "地図で一気見！", font=font("black", 60), fill=PAL["red"], anchor="lt", stroke_width=7,
           stroke_fill=PAL["white"])
    y = 190
    for line in ("古代ギリシア", "→ローマ誕生"):
        d.text((42, y), line, font=font("black", 112), fill=PAL["ink"], anchor="lt", stroke_width=10,
               stroke_fill=PAL["white"])
        y += 140
    tag = "受験の流れも総まとめ"
    f = font("black", 46)
    tw = text_w(tag, f)
    d.rounded_rectangle([44, y + 30, 44 + tw + 60, y + 110], radius=40, fill=PAL["ink"])
    d.text((74, y + 70), tag, font=f, fill=PAL["gold"], anchor="lm")
    im.alpha_composite(L)
    im.convert("RGB").save(path)
    return path


